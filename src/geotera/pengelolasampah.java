    private void tabelPengelolasampahMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelPengelolasampahMouseClicked
        // TODO add your handling code here:
        int baris = tabelPengelolasampah.rowAtPoint(evt.getPoint());
        String idpengelola = tabelPengelolasampah.getValueAt(baris, 1).toString();
        txtIdpengelola.setText(idpengelola);

        String idpembelian = tabelPengelolasampah.getValueAt(baris, 2).toString();
        txtIdpembelian.setText(idpembelian);

        String namaperusahaan = tabelPengelolasampah.getValueAt(baris, 3).toString();
        txtNamaperusahaan.setText(namaperusahaan);

        String emailperusahaan = tabelPengelolasampah.getValueAt(baris, 4).toString();
        txtEmailperusahaan.setText(emailperusahaan);
        
        String alamatperusahaan = tabelPengelolasampah.getValueAt(baris, 5).toString();
        txtAlamatperusahaan.setText(alamatperusahaan);
        
        String kebutuhan = tabelPengelolasampah.getValueAt(baris, 6).toString();
        cbKebutuhan.setSelectedItem(kebutuhan);

    }//GEN-LAST:event_tabelPengelolasampahMouseClicked

