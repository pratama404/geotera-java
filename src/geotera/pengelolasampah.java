        private void tampilkan_data(){
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("No.");
        model.addColumn("Id Pengelola");
        model.addColumn("Id Pembelian");
        model.addColumn("Nama Perusahaan");
        model.addColumn("Email Perusahaan");
        model.addColumn("Alamat Perusahaan");
        model.addColumn("Kebutuhan");
        
        try{
            int no = 1;
            String sql = "SELECT * FROM pengelolasampah";
            java.sql.Connection conn = (Connection)konfig.configDB();
            java.sql.Statement stm = conn.createStatement();
            java.sql.ResultSet res = stm.executeQuery(sql);
            
            while(res.next()){
                model.addRow(new Object[]{no++,res.getString(1),res.getString(2),res.getString(3),res.getString(4),res.getString(5),res.getString(6)});
            }
            tabelPengelolasampah.setModel(model);
            
        }catch (SQLException e) {
            System.out.println("Error : " + e.getMessage());
        }
    }

