    private void tabelPembayaranMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelPembayaranMouseClicked
        // TODO add your handling code here:
        int baris = tabelPembayaran.rowAtPoint(evt.getPoint());
        String idpembayaran = tabelPembayaran.getValueAt(baris, 1).toString();
        txtIdpembayaran.setText(idpembayaran);

        String idpembelian = tabelPembayaran.getValueAt(baris, 2).toString();
        txtIdpembelian.setText(idpembelian);

        String diskon = tabelPembayaran.getValueAt(baris, 3).toString();
        txtDiskon.setText(diskon);

        String voucher = tabelPembayaran.getValueAt(baris, 4).toString();
        txtVoucher.setText(voucher);
        
        String totalpembayaran = tabelPembayaran.getValueAt(baris, 4).toString();
        txtTotalpembayaran.setText(totalpembayaran);

        String sistempembayaran = tabelPembayaran.getValueAt(baris, 5).toString();
        cbSistempembayaran.setSelectedItem(sistempembayaran);
    }//GEN-LAST:event_tabelPembayaranMouseClicked

