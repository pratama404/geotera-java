    private void tabelSampahMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelSampahMouseClicked
        // TODO add your handling code here:
        int baris = tabelSampah.rowAtPoint(evt.getPoint());
        String idsampah = tabelSampah.getValueAt(baris, 1).toString();
        txtIdsampah.setText(idsampah);
        
        String idpembelian = tabelSampah.getValueAt(baris, 2).toString();
        txtIdpembelian.setText(idpembelian);
        
        String keterangan = tabelSampah.getValueAt(baris, 3).toString();
        txtKeterangan.setText(keterangan);
        
        String massa = tabelSampah.getValueAt(baris, 4).toString();
        txtMassa.setText(massa);
        
        String jenis = tabelSampah.getValueAt(baris, 5).toString();
        cbJenis.setSelectedItem(jenis);
        

    }//GEN-LAST:event_tabelSampahMouseClicked

