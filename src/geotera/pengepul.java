    private void tabelPengepulMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelPengepulMouseClicked
        // TODO add your handling code here:
        int baris = tabelPengepul.rowAtPoint(evt.getPoint());
        String idpengepul = tabelPengepul.getValueAt(baris, 1).toString();
        txtIdpengepul.setText(idpengepul);
        
        String namapengepul = tabelPengepul.getValueAt(baris, 2).toString();
        txtNamapengepul.setText(namapengepul);
        
        String email = tabelPengepul.getValueAt(baris, 3).toString();
        txtEmail.setText(email);
        
        String notelp = tabelPengepul.getValueAt(baris, 4).toString();
        txtNotelp.setText(notelp);
        
        String sim = tabelPengepul.getValueAt(baris, 4).toString();
        txtSim.setText(sim);
    }//GEN-LAST:event_tabelPengepulMouseClicked

